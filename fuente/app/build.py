import base64, json, os, sys
d = os.path.dirname(os.path.abspath(__file__))
t = open(os.path.join(d, "template.html"), encoding="utf-8").read()
safe = lambda x: x.replace("</script", "<\\/script").replace("</SCRIPT", "<\\/SCRIPT")
t = t.replace("__FICHAJS__", open(os.path.join(d, "ficha.js"), encoding="utf-8").read())
t = t.replace("__SENDJS__", open(os.path.join(d, "send.js"), encoding="utf-8").read())
t = t.replace("__LABJS__", open(os.path.join(d, "lab.js"), encoding="utf-8").read())
t = t.replace("__XLSXJS__", open(os.path.join(d, "xlsx.js"), encoding="utf-8").read())
t = t.replace("__SIVEJS__", open(os.path.join(d, "sive.js"), encoding="utf-8").read().replace("__SIVEEV__", open(os.path.join(d, "sive_eventos.json"), encoding="utf-8").read()).replace("__CIE10__", safe(json.dumps(open(os.path.join(d, "cie10.txt"), encoding="utf-8").read(), ensure_ascii=False))))
t = t.replace("__GROWTHJS__", open(os.path.join(d, "growth.js"), encoding="utf-8").read().replace("__GROWTH__", open(os.path.join(d, "../who/growth.json")).read()))
t = t.replace("__ATENCION__", open(os.path.join(d, "atencion.js"), encoding="utf-8").read())
uri = lambda f: (lambda b: b if b.startswith("data:") else "data:image/png;base64," + b)(open(os.path.join(d, f)).read().strip())
t = t.replace("__LOGO__", uri("logo.b64"))
t = t.replace("__WM__", uri("wm.b64"))
t = t.replace("__FAV__", uri("fav.b64"))
t = t.replace("__QRLIB__", safe(open(os.path.join(d, "vendor/package/qrcode.js"), encoding="utf-8").read()))
t = t.replace("__MSPDATA__", safe(open(os.path.join(d, "../msp/forms.json"), encoding="utf-8").read()))
t = t.replace("__MSPJS__", safe(open(os.path.join(d, "../msp/msp.js"), encoding="utf-8").read()))
open(os.path.join(d, "Signo Consultorio.html"), "w", encoding="utf-8").write(t)
print("ok", len(t))
